// Generates public/vo/<id>.mp3 + src/vo.ts (speech duration in seconds).
// Uses edge-tts (free Microsoft neural voices, id-ID) — far less robotic than macOS `say`.
//   pipx install edge-tts
// Run: npm run vo
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync, rmSync } from "node:fs";
import { scenes, VOICES } from "../src/script.ts";

const OUT = "public/vo";
const EDGE_TTS = `${process.env.HOME}/.local/bin/edge-tts`;

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const durations = {};
for (const s of scenes) {
  const mp3 = `${OUT}/${s.id}.mp3`;
  const v = VOICES[s.voice ?? "narrator"];
  execFileSync(EDGE_TTS, [
    "--voice",
    v.name,
    `--rate=${v.rate}`,
    `--pitch=${v.pitch}`,
    "--text",
    s.vo,
    "--write-media",
    mp3,
  ]);
  const info = execFileSync("afinfo", [mp3]).toString();
  const match = info.match(/estimated duration: ([\d.]+) sec/);
  if (!match) throw new Error(`no duration for ${s.id}`);
  durations[s.id] = Number(match[1]);
}

writeFileSync(
  "src/vo.ts",
  `// GENERATED by scripts/voiceover.mjs — do not edit. Speech duration in seconds per scene id.\nexport const voDurations: Record<string, number> = ${JSON.stringify(durations, null, 2)};\n`,
);
const total = Object.values(durations).reduce((a, b) => a + b, 0);
console.log(`${scenes.length} clips, speech ${total.toFixed(1)}s (${(total / 60).toFixed(2)} min)`);
